def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)

# Fashion-MNIST: 60.000 train + 10.000 test. Transformasi dinyatakan eksplisit.
